import requests
import pandas as pd
from bs4 import BeautifulSoup
import time

data = []

# Scrape 5 pages (20 books per page)
for page in range(1, 6):

    url = f"https://books.toscrape.com/catalogue/page-{page}.html"

    response = requests.get(url, timeout=20)
    print("Page:", page, "| Status:", response.status_code)

    response.raise_for_status()

    soup = BeautifulSoup(response.content, "html.parser")

    books = soup.select("article.product_pod")

    for book in books:

        title = book.select_one("h3 a")["title"]

        price = book.select_one("p.price_color").get_text(strip=True)
        price = price.replace("£", "").replace("Â", "").strip()

        rating_element = book.select_one("p.star-rating")
        rating = rating_element["class"][1]

        availability = book.select_one("p.availability")
        stock = availability.get_text(" ", strip=True)

        data.append([
            title,
            price,
            rating,
            stock
        ])

    print("Books collected:", len(data))

    time.sleep(1)

# Create dataset
df = pd.DataFrame(
    data,
    columns=["Title", "Price", "Rating", "Availability"]
)

# Clean price for analysis
df["Price"] = pd.to_numeric(df["Price"], errors="coerce")

# Save updated CSV
df.to_csv("books_dataset.csv", index=False, encoding="utf-8-sig")

print("\nScraping completed!")
print("Dataset shape:", df.shape)
