import pandas as pd
import matplotlib.pyplot as plt

df = pd.read_csv("books_dataset.csv")

print("Dataset loaded successfully!")
print("Dataset Shape:", df.shape)

display(df.head(10))

"""# Exploratory Data Analysis (EDA)

## Questions for Analysis

1. What is the average price of the books?
2. Which rating is most common among the books?
3. Are there any unusually expensive or inexpensive books?
4. How are book prices distributed?
5. Is there any relationship between book rating and price?
6. Are there any missing or duplicate records in the dataset?
7. Are all books shown as available?
"""

# Clean Price column
df["Price"] = (
    df["Price"]
    .astype(str)
    .str.replace("£", "", regex=False)
    .str.replace("Â", "", regex=False)
    .str.replace("Ã‚", "", regex=False)
    .str.strip()
)

df["Price"] = pd.to_numeric(df["Price"], errors="coerce")

# Convert ratings from words to numbers
rating_map = {
    "One": 1,
    "Two": 2,
    "Three": 3,
    "Four": 4,
    "Five": 5
}

df["Rating"] = (
    df["Rating"]
    .astype(str)
    .str.strip()
    .str.title()
    .map(rating_map)
)

print("Price and Rating cleaned successfully!")
print(df[["Price", "Rating"]].head(10))
print("\nData types:")
print(df.dtypes)

print("First 10 Records:")
display(df.head(10))

print("\nDataset Shape:")
print(df.shape)

print("\nColumn Names:")
print(df.columns.tolist())

print("\nDataset Information:")
df.info()

print("\nStatistical Summary:")
display(df.describe())

average_price = df["Price"].mean()

print("Average Book Price: £", round(average_price, 2))

rating_counts = df["Rating"].value_counts().sort_index()

print("Rating Frequencies:")
print(rating_counts)

most_common_rating = df["Rating"].mode()

if not most_common_rating.empty:
    print(
        "Most Common Rating:",
        ", ".join(str(int(r)) for r in most_common_rating)
    )
else:
    print("No valid ratings available.")

Q1 = df["Price"].quantile(0.25)
Q3 = df["Price"].quantile(0.75)

IQR = Q3 - Q1

lower_limit = Q1 - 1.5 * IQR
upper_limit = Q3 + 1.5 * IQR

outliers = df[
    (df["Price"] < lower_limit) |
    (df["Price"] > upper_limit)
]

print("Lower Price Limit:", round(lower_limit, 2))
print("Upper Price Limit:", round(upper_limit, 2))
print("Number of Unusual Books:", len(outliers))

display(outliers[["Title", "Price", "Rating"]])

plt.figure(figsize=(8, 5))

plt.hist(df["Price"].dropna(), bins=15, edgecolor="black")

plt.title("Distribution of Book Prices")
plt.xlabel("Price (£)")
plt.ylabel("Number of Books")

plt.tight_layout()
plt.show()

correlation_data = df[["Price", "Rating"]].dropna()

if len(correlation_data) >= 2:
    correlation = correlation_data["Price"].corr(
        correlation_data["Rating"]
    )

    print("Price-Rating Correlation:", round(correlation, 3))

    plt.figure(figsize=(8, 5))

    plt.scatter(
        correlation_data["Rating"],
        correlation_data["Price"]
    )

    plt.title("Book Rating vs Price")
    plt.xlabel("Rating (1 to 5)")
    plt.ylabel("Price (£)")

    plt.xticks([1, 2, 3, 4, 5])
    plt.tight_layout()
    plt.show()
else:
    print("Not enough valid records to calculate correlation.")

from scipy.stats import pearsonr

if len(correlation_data) >= 3:
    r, p_value = pearsonr(
        correlation_data["Price"],
        correlation_data["Rating"]
    )

    print("Correlation:", round(r, 3))
    print("P-value:", round(p_value, 4))

    if p_value < 0.05:
        print("Reject H0: There is evidence of a linear relationship.")
    else:
        print("Fail to reject H0: There is insufficient evidence of a linear relationship.")

print("Missing Values:")
print(df.isnull().sum())

print("\nTotal Missing Values:", df.isnull().sum().sum())

print("\nDuplicate Records:", df.duplicated().sum())

print("Availability Counts:")
print(df["Availability"].value_counts(dropna=False))

print("\nUnique Availability Values:")
print(df["Availability"].unique())

print("Price Statistics:")
print(df["Price"].describe())

print("\nRating Frequencies:")
print(df["Rating"].value_counts().sort_index())

print("\nUnusual Books:")
display(outliers[["Title", "Price", "Rating"]])

print("\nAvailability Pattern:")
print(df["Availability"].value_counts(dropna=False))

plt.figure(figsize=(8, 5))

plt.boxplot(df["Price"].dropna())

plt.title("Book Price Distribution and Potential Outliers")
plt.ylabel("Price (£)")

plt.tight_layout()
plt.show()

print("Final Dataset Shape:", df.shape)

print("\nMissing Values:")
print(df.isnull().sum())

print("\nDuplicate Records:", df.duplicated().sum())

print("\nData Types:")
print(df.dtypes)

print("\nFinal Preview:")
display(df.head(10))